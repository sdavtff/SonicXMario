import { chromium } from '/opt/node-tools/node_modules/playwright/index.mjs';
import { readFileSync } from 'fs';
import { ROUTES } from './routes.mjs';
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 640, height: 300 } });
await page.addInitScript(() => { localStorage.setItem('dashkingdom_save_v1', JSON.stringify({ unlocked: 5, character: 'zip', settings: { quality: 'low', music: 0, sfx: 0 } })); });
await page.goto('http://127.0.0.1:8123/index.html');
await page.waitForFunction(() => window.__test);
await page.evaluate(() => window.__app.startLevel(0));
await page.waitForFunction(() => window.__app.state === 'playing');
await page.evaluate(() => { window.__app.state = 'test'; });
await page.addScriptTag({ content: readFileSync('./bot.js', 'utf8') });
const r = await page.evaluate((route) => {
  const p = window.__app.game.player;
  let st = p.state; window.__stk = [];
  Object.defineProperty(p, 'state', { get() { return st; }, set(v) { if (st === 'rail' && v !== 'rail') window.__stk.push(v + ' ' + p.pos.toArray().map(x=>x.toFixed(2)) + '\n' + new Error().stack.split('\n').slice(1, 5).join('\n')); st = v; } });
  const pos = p.body.pos; const origSet = pos.set.bind(pos);
  pos.set = function (x, y, z) { if (st === 'rail' && y < 0) window.__stk.push('POS SET ' + [x, y, z] + '\n' + new Error().stack.split('\n').slice(1, 5).join('\n')); return origSet(x, y, z); };
  const res = window.__bot(route.slice(0, 13), { maxTime: 40 });
  return { res: res.reason, stk: window.__stk.slice(0, 4) };
}, ROUTES.green);
console.log(JSON.stringify(r, null, 1));
await browser.close();
